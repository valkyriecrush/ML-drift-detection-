"""
Diagnostic Report Generator (6th agent, optional).

Problem this module solves: each agent (DriftDetector, TargetDriftAgent,
PerformanceDriftAgent) already computes a very detailed diagnosis (PSI +
Wasserstein per feature, std_score per metric, SHAP/VIF rationale...), and
AlertAgent already turns that into expert-level `recommended_action` text,
case by case. But all of that:

1. Gets PUSHED (log/Slack/email) then lost -- AlertDispatcher isn't meant
   to be re-read as a report, only to notify in the moment.
2. Gets TRUNCATED before the alert: `AlertAgent.process_data_drift` only
   mentions the first 5 features per priority group (`group[:5]`) in the
   message -- correct to avoid flooding Slack, but means an engineer who
   wants to see all 12 drifted features has nowhere to look.
3. Only exists as individual Alert/RemediationAction objects -- there's
   never a SINGLE coherent artifact answering "what happened this cycle,
   across every drift type, with full detail and recommended remediation"
   -- the equivalent of an incident report an engineer can open.

This module doesn't recompute anything or reinvent any decision logic: it
reads the results already produced by the 3 detectors + the Alert/
RemediationAction objects already generated by AlertAgent/RemediationAgent,
and ASSEMBLES them into a single DiagnosticReport, complete (no 5-item
truncation), rendered as Markdown (readable, directly usable by an
engineer) + JSON (archivable, queryable), and PERSISTED to disk -- unlike
alerts, which are only a transient stream.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
import io
import json
import logging
import re
from pathlib import Path
from typing import Any, Dict, List, Optional

# Aliased (not "markdown") because DiagnosticReportGenerator.save() already
# uses a local variable named `markdown` for the report's Markdown text --
# keeping the import name distinct avoids any risk of shadowing confusion.
import markdown as _markdown_to_html
from xhtml2pdf import pisa

from alert_agent import Alert, AlertPriority
from drift_detector import DriftReport
from feature_intelligence import FeatureIntelligenceContext, FeatureRiskAssessor
from performance_drift_agent import PerformanceDriftResult
from remediation_agent import RemediationAction
from target_drift_agent import LabelStatus, TargetDriftResult

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------- #
# Overall status: reuses the MAX priority already computed by AlertAgent
# instead of re-deriving overall severity independently -- two synthesis
# paths that could diverge on the same data would be the same class of bug
# psi_common.py already fixed once for PSI (see drift_detector.py).
# ---------------------------------------------------------------------- #

_STATUS_BY_PRIORITY = {
    AlertPriority.PAGE: "page",
    AlertPriority.CRITICAL: "critical",
    AlertPriority.WARNING: "degraded",
    AlertPriority.INFO: "info",
}
_STATUS_RANK = {"healthy": 0, "info": 1, "degraded": 2, "critical": 3, "page": 4}


def _overall_status(alerts: List[Alert]) -> str:
    status = "healthy"
    for a in alerts:
        candidate = _STATUS_BY_PRIORITY.get(a.priority, "info")
        if _STATUS_RANK[candidate] > _STATUS_RANK[status]:
            status = candidate
    return status


