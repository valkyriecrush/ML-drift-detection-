@dataclass
class DiagnosticReport:
    model_id: str
    cycle_timestamp: str          # timestamp of the most recent signal used (traceability)
    generated_at: str
    overall_status: str           # "healthy" | "info" | "degraded" | "critical" | "page"
    executive_summary: str
    data_drift: Optional[Dict[str, Any]]
    target_drift: Optional[Dict[str, Any]]
    performance_drift: Optional[Dict[str, Any]]
    root_cause: Optional[Dict[str, Any]]
    alerts: List[Dict[str, Any]]
    remediation_actions: List[Dict[str, Any]]

    def to_dict(self) -> Dict[str, Any]:
        return {
            "model_id": self.model_id,
            "cycle_timestamp": self.cycle_timestamp,
            "generated_at": self.generated_at,
            "overall_status": self.overall_status,
            "executive_summary": self.executive_summary,
            "data_drift": self.data_drift,
            "target_drift": self.target_drift,
            "performance_drift": self.performance_drift,
            "root_cause": self.root_cause,
            "alerts": self.alerts,
            "remediation_actions": self.remediation_actions,
        }

    # ------------------------------------------------------------------ #
    # Markdown rendering -- THE format meant for an engineer to read: full
    # detail (no 5-item truncation like in alert messages), one page to
    # open to understand a whole monitoring cycle.
    # ------------------------------------------------------------------ #

    def to_markdown(self) -> str:
        lines: List[str] = []
        badge = {"healthy": "🟢", "info": "🔵", "degraded": "🟡", "critical": "🔴", "page": "🚨"}
        lines.append(f"# Diagnostic report -- `{self.model_id}`")
        lines.append("")
        lines.append(f"**Overall status: {badge.get(self.overall_status, '')} {self.overall_status.upper()}**")
        lines.append(f"Generated at {self.generated_at} | Cycle (most recent signal): {self.cycle_timestamp}")
        lines.append("")
        lines.append("## Executive summary")
        lines.append("")
        lines.append(self.executive_summary)
        lines.append("")

        if self.root_cause:
            lines.append("## 🔴 Probable root cause identified (cross-agent corroboration)")
            lines.append("")
            lines.append(f"**{self.root_cause['title']}**")
            lines.append("")
            lines.append(self.root_cause["message"])
            lines.append("")
            lines.append(f"**Recommended action:** {self.root_cause['recommended_action']}")
            lines.append("")

        if self.data_drift:
            lines.extend(self._render_data_drift())
        if self.target_drift:
            lines.extend(self._render_target_drift())
        if self.performance_drift:
            lines.extend(self._render_performance_drift())

        lines.extend(self._render_alerts())
        lines.extend(self._render_remediation())

        return "\n".join(lines)

    # -- Detailed sections, one per drift type -----------------------

    def _render_data_drift(self) -> List[str]:
        d = self.data_drift
        out = [
            "## 1. Data / Feature Drift",
            "",
            f"Overall severity: **{d['overall_severity']}** -- "
            f"{d['drifted_features']}/{d['total_features']} feature(s) drifted "
            f"({d['drift_percentage']:.1f}%).",
            "",
        ]
        rows = d["features"]
        if rows:
            has_risk = any(r.get("risk_level") for r in rows)
            has_quality_issue = any(
                (r.get("missing_rate") or 0) >= 0.05 or r.get("new_categories") for r in rows
            )
            header = ["Feature", "Type", "PSI", "Wasserstein (norm)", "Severity", "Drifted"]
            if has_quality_issue:
                header += ["Quality"]
            if has_risk:
                header += ["Risk Level (SHAP/VIF)", "Rationale"]
            out.append("| " + " | ".join(header) + " |")
            out.append("|" + "---|" * len(header))
            for r in rows:
                row = [
                    r["feature"], r["type"], f"{r['psi_score']:.4f}",
                    f"{r['norm_wasserstein_distance']:.4f}" if r["norm_wasserstein_distance"] is not None else "n/a",
                    r["severity"], "yes" if r["is_drifted"] else "no",
                ]
                if has_quality_issue:
                    missing_rate = r.get("missing_rate")
                    new_cats = r.get("new_categories") or []
                    flags = []
                    if missing_rate is not None and missing_rate >= 0.05:
                        flags.append(f"⚠️ {missing_rate*100:.1f}% missing")
                    if new_cats:
                        flags.append(f"⚠️ new: {', '.join(new_cats[:3])}")
                    row += [" / ".join(flags) if flags else "ok"]
                if has_risk:
                    row += [r.get("risk_level") or "n/a", (r.get("rationale") or "").replace("|", "/")]
                out.append("| " + " | ".join(row) + " |")
            out.append("")
        return out

    def _render_target_drift(self) -> List[str]:
        t = self.target_drift
        out = ["## 2. Target Drift", "", f"Status: **{t['status']}** | n_samples = {t['n_samples']}", ""]
        if t["drift"] is None:
            out.append("No computation this cycle (PENDING -- no usable labels/predictions yet).")
        else:
            drift = t["drift"]
            out.append(f"PSI = {drift['psi_score']:.4f} | severity = **{drift['severity']}** | drifted = {'yes' if drift['is_drifted'] else 'no'}")
            if drift.get("norm_wasserstein_distance") is not None:
                out.append(f"Wasserstein distance (normalized) = {drift['norm_wasserstein_distance']:.4f}")
            details = drift.get("details") or {}
            if "chi2_statistic" in details and details["chi2_statistic"] is not None:
                out.append(f"Chi2 = {details['chi2_statistic']:.3f} (p-value = {details['chi2_pvalue']:.4f})")
            elif details.get("chi2_note"):
                out.append(f"Chi2 skipped: {details['chi2_note']}")
            if "reference_mean" in details:
                out.append(
                    f"Reference mean = {details['reference_mean']:.4f} -> "
                    f"current mean = {details['current_mean']:.4f} "
                    f"(reference std = {details['reference_std']:.4f} -> current std = {details['current_std']:.4f})"
                )
            if details.get("note"):
                out.append(f"_Note: {details['note']}_")
        out.append("")
        return out

    def _render_performance_drift(self) -> List[str]:
        p = self.performance_drift
        out = [
            "## 3. Performance Drift", "",
            f"Status: **{p['status']}** | severity: **{p['severity']}** | "
            f"remediation_type: `{p['remediation_type']}` | window = {p['window_size']} samples",
        ]
        if p.get("proba_coverage") is not None:
            out.append(f"y_proba coverage over the window: {p['proba_coverage']*100:.1f}%")
        out.append("")

        def _metric_table(title: str, metrics: List[Dict[str, Any]]) -> List[str]:
            if not metrics:
                return []
            lines = [f"### {title}", "", "| Metric | Baseline | Current | Delta | Std score | Degraded | Contributes to severity |", "|---|---|---|---|---|---|---|"]
            for m in metrics:
                lines.append(
                    f"| {m['name']} | {m['baseline']:.4f} | {m['current']:.4f} | {m['delta']:+.4f} | "
                    f"{m['std_score']:+.2f} | {'yes' if m['degraded'] else 'no'} | {'yes' if m.get('contributes_to_severity', True) else 'no'} |"
                )
            lines.append("")
            return lines

        out.extend(_metric_table("Performance metrics", p["metrics"]))
        out.extend(_metric_table("Calibration metrics", p["calibration_metrics"]))

        if p.get("notes"):
            out.append("**Notes:**")
            for n in p["notes"]:
                out.append(f"- {n}")
            out.append("")
        return out

    def _render_alerts(self) -> List[str]:
        if not self.alerts:
            return ["## Alerts raised this cycle", "", "None.", ""]
        out = [f"## Alerts raised this cycle ({len(self.alerts)})", ""]
        order = {"page": 0, "critical": 1, "warning": 2, "info": 3}
        for a in sorted(self.alerts, key=lambda x: order.get(x["priority"], 9)):
            icon = {"page": "🚨", "critical": "🔴", "warning": "🟡", "info": "🔵"}.get(a["priority"], "")
            out.append(f"### {icon} [{a['priority'].upper()}] {a['title']} _(source: {a['source_agent']})_")
            out.append("")
            out.append(a["message"].replace("\n", "  \n"))
            out.append("")
            if a.get("recommended_action"):
                out.append(f"**Recommended action (expert):** {a['recommended_action']}")
                out.append("")
            out.append(f"_Remediation type: `{a['remediation_type']}`_")
            out.append("")
        return out

    def _render_remediation(self) -> List[str]:
        if not self.remediation_actions:
            return ["## Remediation actions", "", "None generated this cycle.", ""]
        out = [f"## Remediation actions ({len(self.remediation_actions)})", "",
               "| Type | Urgency (SLA) | Status | Approval required | Automatable | Source alert |",
               "|---|---|---|---|---|---|"]
        for r in self.remediation_actions:
            urgency = r.get("urgency", "normal")
            sla = r.get("sla", "")
            label = f"{urgency} ({sla})" if sla else urgency
            if r.get("is_primary") is False and r.get("superseded_by"):
                label += f" -- superseded by '{r['superseded_by']}'"
            out.append(
                f"| {r['action_type']} | {label} | {r['status']} | {'yes' if r['requires_approval'] else 'no'} | "
                f"{'yes' if r['automatable'] else 'no'} | {r['source_alert_title']} |"
            )
        out.append("")
        return out


