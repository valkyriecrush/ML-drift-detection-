# Add to MonitoringState (TypedDict): `report_path: str`,
# `report_pdf_path: Optional[str]`, and `report_status: str` --
# deliberately NOT the report content itself (potentially long Markdown/
# PDF bytes) in the checkpointed State, only on-disk paths, same logic as
# features_df/_BATCH_DATA.
# ---------------------------------------------------------------------- #

def report_node(state: Dict[str, Any], generator: Optional[DiagnosticReportGenerator] = None) -> Dict[str, Any]:
    """Assembles and persists the current cycle's DiagnosticReport.

    Reads `state["_alert_objects"]` (set by alerting_node) and
    `state["_remediation_action_objects"]` (set by remediation_node) -- the
    RAW objects for the current cycle, not their serialized/capped history."""
    generator = generator or DiagnosticReportGenerator()

    report = generator.generate(
        model_id=state["model_id"],
        data_drift_report=state.get("data_drift_report"),
        target_drift_result=state.get("target_drift_result"),
        performance_drift_result=state.get("performance_drift_result"),
        alerts=state.get("_alert_objects", []),
        remediation_actions=state.get("_remediation_action_objects", []),
    )
    paths = generator.save(report)

    logger.info(
        f"[{state['model_id']}] Diagnostic report ({report.overall_status}) -> "
        f"{paths.get('pdf_path') or paths['markdown_path']}"
    )

    return {
        **state,
        "report_path": paths["markdown_path"],
        # Absent (None) if PDF rendering failed this cycle -- see
        # DiagnosticReportGenerator.save()'s docstring on why that's
        # best-effort rather than fatal.
        "report_pdf_path": paths.get("pdf_path"),
        "report_status": report.overall_status,
        # Short (1-3 sentence) plain-language summary, cheap enough to keep
        # in checkpointed state as-is (unlike the full Markdown, kept only
        # on disk). Lets a caller (e.g. run_scenario.py) send a short
        # professional email with the full technical report attached,
        # instead of dumping PSI tables/rationale into the email body.
        "report_executive_summary": report.executive_summary,
    }
