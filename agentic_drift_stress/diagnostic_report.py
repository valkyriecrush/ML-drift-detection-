# Generator
# ---------------------------------------------------------------------- #

class DiagnosticReportGenerator:
    """Assembles a DiagnosticReport from the outputs ALREADY computed by the
    3 detectors + the Alert/RemediationAction objects already produced, and
    persists it to disk. Recomputes and redecides nothing -- pure
    presentation/archival layer on top of the existing agents."""

    def __init__(self, output_dir: str = "reports"):
        self.output_dir = Path(output_dir)

    # -- Construction ------------------------------------------------------

    def generate(
        self,
        model_id: str,
        data_drift_report: Optional[DriftReport] = None,
        target_drift_result: Optional[TargetDriftResult] = None,
        performance_drift_result: Optional[PerformanceDriftResult] = None,
        alerts: Optional[List[Alert]] = None,
        remediation_actions: Optional[List[RemediationAction]] = None,
        feature_intelligence: Optional[FeatureIntelligenceContext] = None,
    ) -> DiagnosticReport:
        alerts = alerts or []
        remediation_actions = remediation_actions or []

        assessor = FeatureRiskAssessor(feature_intelligence) if feature_intelligence is not None else None

        data_drift_dict = self._render_data_drift_section(data_drift_report, assessor) if data_drift_report else None
        target_drift_dict = self._render_target_drift_section(target_drift_result) if target_drift_result else None
        performance_dict = performance_drift_result.to_dict() if performance_drift_result else None

        root_cause_alert = next((a for a in alerts if a.source_agent == "root_cause"), None)
        root_cause_dict = (
            {"title": root_cause_alert.title, "message": root_cause_alert.message,
             "recommended_action": root_cause_alert.recommended_action}
            if root_cause_alert else None
        )

        cycle_timestamp = max(
            [t.timestamp for t in (data_drift_report, target_drift_result, performance_drift_result) if t is not None],
            default=datetime.now(timezone.utc).isoformat(),
        )

        report = DiagnosticReport(
            model_id=model_id,
            cycle_timestamp=cycle_timestamp,
            generated_at=datetime.now(timezone.utc).isoformat(),
            overall_status=_overall_status(alerts),
            executive_summary=self._executive_summary(
                alerts, remediation_actions, data_drift_report, target_drift_result, performance_drift_result
            ),
            data_drift=data_drift_dict,
            target_drift=target_drift_dict,
            performance_drift=performance_dict,
            root_cause=root_cause_dict,
            alerts=[a.to_dict() for a in alerts],
            remediation_actions=[r.to_dict() for r in remediation_actions],
        )
        return report

    @staticmethod
    def _render_data_drift_section(report: DriftReport, assessor: Optional[FeatureRiskAssessor]) -> Dict[str, Any]:
        features = []
        for r in report.feature_results:  # ALL features, not just the first 5 (see module docstring)
            entry = {
                "feature": r.feature_name,
                "type": r.feature_type.value,
                "psi_score": r.psi_score,
                "norm_wasserstein_distance": r.norm_wasserstein_dist,
                "severity": r.severity.value,
                "is_drifted": r.is_drifted,
                "risk_level": None,
                "rationale": None,
                "missing_rate": r.details.get("missing_rate"),
                "new_categories": r.details.get("new_categories") or [],
            }
            if assessor is not None:
                try:
                    assessment = assessor.assess(r.feature_name)
                    entry["risk_level"] = assessment.risk_level.value
                    entry["rationale"] = assessment.rationale
                except Exception as exc:  # noqa: BLE001 -- feature missing from SHAP/VIF context, degrade gracefully
                    logger.debug(f"No risk assessment for '{r.feature_name}': {exc}")
            features.append(entry)

        return {
            "overall_severity": report.overall_severity.value,
            "total_features": report.total_features,
            "drifted_features": report.drifted_features,
            "drift_percentage": report.drift_percentage,
            "features": features,
            "timestamp": report.timestamp,
        }

    @staticmethod
    def _render_target_drift_section(result: TargetDriftResult) -> Dict[str, Any]:
        return result.to_dict()

    @staticmethod
    def _executive_summary(
        alerts: List[Alert],
        remediation_actions: List[RemediationAction],
        data_drift_report: Optional[DriftReport],
        target_drift_result: Optional[TargetDriftResult],
        performance_drift_result: Optional[PerformanceDriftResult],
    ) -> str:
        parts: List[str] = []

        if data_drift_report is not None:
            parts.append(
                f"Data drift: {data_drift_report.drifted_features}/{data_drift_report.total_features} "
                f"feature(s) drifted (severity {data_drift_report.overall_severity.value})."
            )
        if target_drift_result is not None and target_drift_result.status != LabelStatus.PENDING and target_drift_result.drift:
            parts.append(
                f"Target drift ({target_drift_result.status.value}): "
                f"PSI={target_drift_result.drift.psi_score:.3f}, severity {target_drift_result.drift.severity.value}."
            )
        if performance_drift_result is not None and performance_drift_result.severity is not None:
            parts.append(
                f"Performance: severity {performance_drift_result.severity.value}"
                + (f", cause = {performance_drift_result.remediation_type}." if performance_drift_result.remediation_type else ".")
            )

        counts: Dict[str, int] = {}
        for a in alerts:
            counts[a.priority.value] = counts.get(a.priority.value, 0) + 1
        if counts:
            parts.append("Alerts: " + ", ".join(f"{v} {k}" for k, v in sorted(counts.items(), key=lambda kv: kv[0])) + ".")
        else:
            parts.append("No alerts raised this cycle.")

        pending = sum(1 for r in remediation_actions if r.requires_approval and r.status != "approved")
        if pending:
            parts.append(f"{pending} remediation action(s) pending human approval.")

        if not parts:
            parts.append("No usable signal this cycle (no detector produced a result).")

        return " ".join(parts)

    # -- PDF rendering ---------------------------------------------------

    # One CSS per overall_status, reusing the same severity palette as the
    # HTML emails (run_scenario.py::_build_executive_email,
    # bridge/senders.py::_render_alert_html) so a PAGE/CRITICAL report is
    # visually unmistakable, not just another gray PDF.
    _STATUS_ACCENT = {
        "page": "#7C0A0A", "critical": "#C0392B", "degraded": "#D68910",
        "info": "#2E86C1", "healthy": "#1E8449",
    }

    # xhtml2pdf has no color-emoji font support -- unlike a terminal or a
    # Markdown viewer, it renders these as solid black tofu boxes, which
    # looks like a rendering bug rather than a badge. The words right next
    # to each emoji already carry the same information ("CRITICAL",
    # "PAGE", the "missing"/"new:" flags), so stripping them loses nothing
    # in the PDF specifically -- the .md/.json files keep the emojis as-is.
    _PDF_STRIP_CHARS = "🟢🔵🟡🔴🚨⚠️"

    def _render_pdf(self, report: "DiagnosticReport", markdown_text: str) -> bytes:
        """Converts the report's Markdown to a styled PDF (Markdown -> HTML
        via `markdown`, HTML -> PDF via `xhtml2pdf`, both pure-Python, no
        system library like wkhtmltopdf/Cairo required). Raises on failure
        -- the caller (save()) decides how to degrade, this method just
        renders."""
        accent = self._STATUS_ACCENT.get(report.overall_status, "#5D6D7E")
        pdf_source = markdown_text
        for ch in self._PDF_STRIP_CHARS:
            pdf_source = pdf_source.replace(ch, "")
        # Collapse the double space left behind on each line (e.g. "## 🔴 Title"
        # -> "##  Title") WITHOUT touching newlines, which Markdown needs
        # (a blank line = paragraph break, a lone "\n" inside a table row
        # matters for pipe alignment).
        pdf_source = "\n".join(re.sub(r"[ \t]{2,}", " ", line) for line in pdf_source.split("\n"))
        body_html = _markdown_to_html.markdown(pdf_source, extensions=["tables", "fenced_code"])

        css = f"""
        <style>
            @page {{ size: A4; margin: 2cm 1.8cm; }}
            body {{ font-family: Helvetica, Arial, sans-serif; font-size: 10.5pt; color: #1C2833; }}
            h1 {{ color: #FFFFFF; background-color: {accent}; padding: 10px 14px;
                  font-size: 16pt; border-radius: 4px; }}
            h2 {{ color: {accent}; border-bottom: 1px solid #EAECEE; padding-bottom: 4px;
                  margin-top: 22px; font-size: 13pt; }}
            h3 {{ color: #1C2833; font-size: 11.5pt; }}
            table {{ border-collapse: collapse; width: 100%; margin: 10px 0 16px; }}
            th {{ background-color: #F4F6F7; border: 1px solid #D5D8DC; padding: 5px 8px;
                  font-size: 9pt; text-align: left; }}
            td {{ border: 1px solid #EAECEE; padding: 5px 8px; font-size: 9pt; }}
            code, pre {{ font-family: Courier, monospace; font-size: 9pt;
                         background-color: #F8F9F9; }}
            strong {{ color: #1C2833; }}
            hr {{ border: none; border-top: 1px solid #EAECEE; }}
            .footer {{ margin-top: 24px; font-size: 8pt; color: #909497; }}
        </style>
        """
        html_full = (
            f"<html><head><meta charset='utf-8'/>{css}</head>"
            f"<body>{body_html}"
            f"<p class='footer'>Generated automatically by the drift monitoring pipeline.</p>"
            f"</body></html>"
        )

        buffer = io.BytesIO()
        result = pisa.CreatePDF(html_full, dest=buffer, encoding="utf-8")
        if result.err:
            raise RuntimeError(f"xhtml2pdf reported {result.err} error(s) rendering the report to PDF")
        return buffer.getvalue()

    # -- Persistence ---------------------------------------------------

    def save(self, report: DiagnosticReport) -> Dict[str, str]:
        """Writes the report as Markdown + JSON + PDF, timestamped, under
        `reports/<model_id>/<timestamp>.{md,json,pdf}`, updates a
        `latest.{md,json,pdf}` pointer for direct access without listing
        the directory, and logs a summary line to `index.jsonl`
        (append-only, same principle as AlertDispatcher's dead-letter
        queue) so the history can be browsed without reopening every
        report.

        PDF rendering is best-effort: on failure (missing dependency,
        malformed Markdown edge case...) the Markdown/JSON files are still
        written and `pdf_path` is simply absent from the returned dict --
        callers (see run_scenario.py) fall back to attaching the Markdown
        file rather than crashing the whole reporting step over a
        cosmetic failure."""
        model_dir = self.output_dir / report.model_id
        model_dir.mkdir(parents=True, exist_ok=True)

        safe_ts = report.generated_at.replace(":", "-")
        md_path = model_dir / f"{safe_ts}.md"
        json_path = model_dir / f"{safe_ts}.json"
        pdf_path = model_dir / f"{safe_ts}.pdf"
        latest_md_path = model_dir / "latest.md"
        latest_json_path = model_dir / "latest.json"
        latest_pdf_path = model_dir / "latest.pdf"
        index_path = model_dir / "index.jsonl"

        markdown = report.to_markdown()
        payload = report.to_dict()

        md_path.write_text(markdown, encoding="utf-8")
        json_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
        latest_md_path.write_text(markdown, encoding="utf-8")
        latest_json_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")

        paths = {
            "markdown_path": str(md_path),
            "json_path": str(json_path),
            "latest_markdown_path": str(latest_md_path),
        }

        try:
            pdf_bytes = self._render_pdf(report, markdown)
            pdf_path.write_bytes(pdf_bytes)
            latest_pdf_path.write_bytes(pdf_bytes)
            paths["pdf_path"] = str(pdf_path)
            paths["latest_pdf_path"] = str(latest_pdf_path)
        except Exception as exc:
            logger.warning(
                f"[{report.model_id}] PDF rendering failed, keeping Markdown/JSON only "
                f"(report itself is not affected): {exc}"
            )

        try:
            with open(index_path, "a", encoding="utf-8") as f:
                f.write(json.dumps({
                    "generated_at": report.generated_at,
                    "cycle_timestamp": report.cycle_timestamp,
                    "overall_status": report.overall_status,
                    "n_alerts": len(report.alerts),
                    "n_remediation_actions": len(report.remediation_actions),
                    "path": str(md_path),
                    "pdf_path": paths.get("pdf_path"),
                }, ensure_ascii=False) + "\n")
        except Exception as exc:
            logger.error(f"Failed to write the report index for '{report.model_id}': {exc}")

        return paths


